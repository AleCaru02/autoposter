import assert from "node:assert/strict";
import { marketingRequest,marketingPrompt,marketingOutput,MARKETING_INSTRUCTIONS } from "../api/_lib/marketing-draft.js";
import { readFileSync } from "node:fs";
const input={profileId:"11111111-1111-4111-8111-111111111111",channel:"META_ADS",objective:"Lead",audience:"PMI",offer:"Demo",evidence:"",budgetEur:"100",brand:"FORGED"};
const parsed=marketingRequest(input);
assert.equal("brand" in parsed,false);
assert.throws(()=>marketingRequest({...input,profileId:"invalid"}));
assert.throws(()=>marketingRequest({...input,budgetEur:"0"}));
assert.throws(()=>marketingRequest({...input,channel:"UNKNOWN"}));
const brand={profileName:"Trusted",industry:null,websiteUrl:null,description:null,businessModel:null,location:null,serviceArea:null,target:null,tone:null,goals:[],confirmedWebsiteContent:[]};
assert.match(marketingPrompt(parsed,brand),/Trusted/);
assert.doesNotMatch(marketingPrompt(parsed,brand),/FORGED/);
assert.match(MARKETING_INSTRUCTIONS,/Non eseguire azioni esterne/);
assert.equal(marketingOutput({status:"completed",output:[{content:[{type:"output_text",text:"Bozza"}]}]}),"Bozza");
assert.throws(()=>marketingOutput({status:"incomplete",output_text:"partial"}));
assert.throws(()=>marketingOutput({output:[]}));
const route=readFileSync("api/marketing-draft.ts","utf8");
assert.ok(route.indexOf("loadEditorialProfile(sql,input.profileId,owner)")<route.indexOf("meter.reserve("));
assert.ok(route.indexOf("if(!budget.allowed)")<route.indexOf('fetch("https://api.openai.com/v1/responses"'));
assert.match(route,/externalActionsExecuted:false/);
assert.match(route,/meter.persistTechnicalEvents/);
console.log("Marketing draft validation, auth boundary and budget contract: PASS");
