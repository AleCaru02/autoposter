import assert from "node:assert/strict";
import { SCENE_MODELS,durationOptions,compareCatalog,sceneEstimate,editorialDraft,SOCIAL_VIDEO_TARGETS } from "../src/features/content/personal-brand-editorial.js";
const kling=SCENE_MODELS.find(m=>m.id==="kling4_0")!;
assert.ok(kling);
assert.equal(durationOptions(kling)[0],3);
assert.equal(durationOptions(kling).at(-1),30);
assert.ok(kling.resolutions.includes("4k"));
const flash=SCENE_MODELS.find(m=>m.id==="kling_4_0_flash")!;
assert.deepEqual(flash.resolutions,["720p"]);
assert.equal(durationOptions(flash).at(-1),20);
assert.equal(sceneEstimate(1,5,0.126),18.9);
assert.equal(sceneEstimate(1,5,null),null);
assert.equal(sceneEstimate(1,5,-1),null);
const delta=compareCatalog([kling],[{...kling,description:"Updated"},flash]);
assert.equal(delta.changed.length,1);
assert.deepEqual(delta.added.map(m=>m.id),[flash.id]);
assert.equal(compareCatalog([kling],[]).removed.length,1);
const plan=editorialDraft([]);
assert.equal(plan.length,30);
assert.equal(new Set(plan.map(x=>x.topic)).size,30);
assert.ok(plan.every(x=>x.status==="DRAFT_REQUIRES_EVIDENCE"&&x.reel&&x.linkedin&&x.proof));
assert.deepEqual(plan[0].videoTargets,SOCIAL_VIDEO_TARGETS);
assert.equal(editorialDraft(["UN SITO BELLO NON BASTA"]).length,29);
console.log("Personal brand editorial preview: PASS");
